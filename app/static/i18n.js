/** Translate a text produced by the server (exact match, pattern, or comma-separated parts). */
function tr(text) {
  if (!text || LANG === "fr") return text;
  if (EN_SERVER[text]) return EN_SERVER[text];
  for (const [rx, out] of EN_PATTERNS) if (rx.test(text)) return text.replace(rx, out);
  if (text.includes(", ")) {
    const parts = text.split(", ");
    const done = parts.map((p) => tr(p));
    if (done.some((p, i) => p !== parts[i])) return done.join(", ");
  }
  return text;
}

