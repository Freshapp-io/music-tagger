function t(key, vars) {
  let s = (LANG === "en" ? EN[key] : FR[key]) ?? FR[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
  return s;
}

/** Translate a text produced by the server (exact match, pattern, or comma-separated parts). */
function tr(text) {
  if (!text || LANG === "fr") return text;
  if (EN_SERVER[text]) return EN_SERVER[text];
  for (const [rx, out] of EN_PATTERNS) if (rx.test(text)) return text.replace(rx, out);
  if (text.includes(", ")) {
    const parts = text.split(", ");
    const done = parts.map((p) => tr(p));
    if (done.some((p, i) => p !== parts[i])) return done.join(", ");
  }
  return text;
}

/** Translate the static parts of a page: data-i18n (text), -title, -placeholder, -aria-label. */
function applyStaticTexts(root = document) {
  for (const el of root.querySelectorAll("[data-i18n]")) el.innerHTML = t(el.dataset.i18n);
  for (const attr of ["title", "placeholder", "aria-label"]) {
    for (const el of root.querySelectorAll(`[data-i18n-${attr}]`)) el.setAttribute(attr, t(el.getAttribute(`data-i18n-${attr}`)));
  }
}

